import { ref } from 'vue';

export const productosCatalogo = ref(structuredClone(defaultProductos));

export const resetProductosCatalogo = () => {
  productosCatalogo.value = [];
};

export const guardarProducto = (producto) => {
  const normalized = {
    ...producto,
    id: Number(producto.id) || Number(Date.now()),
    precio: Number(producto.precio || 0),
    stock: Math.max(0, Number(producto.stock || 0)),
    categoria: ['Belleza', 'Novedades'].includes(producto.categoria) ? producto.categoria : 'Belleza',
    nombre: producto.nombre || 'Producto sin nombre',
    descripcion: producto.descripcion || 'Sin descripción',
    imagen_url: producto.imagen_url || '/logo-empresa.jpeg',
    created_at: producto.created_at || new Date().toISOString(),
  };

  const existingIndex = productosCatalogo.value.findIndex((item) => Number(item.id) === Number(normalized.id));

  if (existingIndex >= 0) {
    productosCatalogo.value[existingIndex] = { ...productosCatalogo.value[existingIndex], ...normalized };
    return productosCatalogo.value[existingIndex];
  }

  productosCatalogo.value = [normalized, ...productosCatalogo.value];
  return normalized;
};

export const actualizarStockProducto = (id, cantidadVendida) => {
  const unidades = Number(cantidadVendida || 0);
  if (!unidades || unidades < 0) return null;

  const item = productosCatalogo.value.find((producto) => Number(producto.id) === Number(id));
  if (!item) return null;

  item.stock = Math.max(0, Number(item.stock || 0) - unidades);
  return item;
};

export const eliminarProducto = (id) => {
  productosCatalogo.value = productosCatalogo.value.filter((item) => Number(item.id) !== Number(id));
};

export const obtenerProducto = (id) =>
  productosCatalogo.value.find((item) => Number(item.id) === Number(id)) ?? null;
